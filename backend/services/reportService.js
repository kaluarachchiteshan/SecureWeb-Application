import PDFDocument from 'pdfkit';

/**
 * Generates a clean, professional PDF security audit report stream.
 */
export const generatePdfReport = (website, scanResult, res) => {
  const doc = new PDFDocument({ margin: 40 });

  // Header & Styling Setup
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename=SecureWeb-Audit-${website.websiteName.replace(/\s+/g, '_')}.pdf`);
  doc.pipe(res);

  // Decorative Top Accent Banner
  doc.rect(0, 0, 612, 15).fill('#0f172a');
  doc.rect(0, 15, 612, 5).fill('#06b6d4');

  // Title & Header Information
  doc.moveDown(1);
  doc.fontSize(22).fillColor('#0f172a').text('SECUREWEB SECURITY AUDIT REPORT', { align: 'left', bold: true });
  doc.fontSize(10).fillColor('#64748b').text('Generated by SecureWeb Security Platform', { align: 'left' });
  doc.moveDown(1);

  // Line Divider
  doc.moveTo(40, 95).lineTo(572, 95).strokeColor('#cbd5e1').stroke();
  doc.moveDown(1.5);

  // Target Website Summary Box
  doc.rect(40, 110, 532, 80).fillAndStroke('#f8fafc', '#e2e8f0');
  
  doc.fontSize(12).fillColor('#1e293b').text(`Website Name: `, 55, 122, { continued: true, bold: true })
     .fillColor('#0284c7').text(`${website.websiteName}`);
  doc.fontSize(11).fillColor('#1e293b').text(`Website URL: `, 55, 140, { continued: true })
     .fillColor('#475569').text(`${website.websiteURL}`);
  doc.fontSize(11).fillColor('#1e293b').text(`Scan Date: `, 55, 158, { continued: true })
     .fillColor('#475569').text(`${new Date(scanResult.scanDate || Date.now()).toLocaleString()}`);

  // Security Score Badge / Box
  const score = scanResult.securityScore;
  let scoreColor = '#10b981'; // Green
  if (score < 40) scoreColor = '#ef4444'; // Red
  else if (score < 65) scoreColor = '#f97316'; // Orange
  else if (score < 85) scoreColor = '#eab308'; // Yellow

  doc.rect(430, 120, 130, 60).fill(scoreColor);
  doc.fontSize(24).fillColor('#ffffff').text(`${score}/100`, 430, 128, { align: 'center', bold: true });
  doc.fontSize(10).fillColor('#ffffff').text(`Risk: ${scanResult.riskLevel.toUpperCase()}`, 430, 158, { align: 'center' });

  // Executive Overview Section
  doc.moveDown(4.5);
  doc.fontSize(14).fillColor('#0f172a').text('1. Executive Security Overview');
  doc.moveDown(0.5);

  doc.fontSize(10).fillColor('#334155');
  doc.text(`HTTPS Protocol Enabled: ${scanResult.httpsEnabled ? 'YES (Secure)' : 'NO (Vulnerable)'}`);
  doc.text(`SSL Certificate Issuer: ${scanResult.sslDetails?.issuer || 'N/A'}`);
  doc.text(`SSL Days Remaining: ${scanResult.sslDetails?.daysRemaining ?? 'N/A'} days`);
  doc.text(`Total Vulnerabilities Identified: ${scanResult.vulnerabilities?.length || 0}`);
  doc.moveDown(1);

  // Security Header Audit Table
  doc.fontSize(14).fillColor('#0f172a').text('2. Security Headers & DNS Audit');
  doc.moveDown(0.5);

  const headers = scanResult.headerAudit || {};
  const dnsAudit = scanResult.dnsAudit || {};
  const headerChecks = [
    { name: 'Strict-Transport-Security (HSTS)', status: headers.hsts },
    { name: 'Content-Security-Policy (CSP)', status: headers.csp },
    { name: 'X-Frame-Options (Clickjacking)', status: headers.xFrameOptions },
    { name: 'X-Content-Type-Options (MIME-Sniffing)', status: headers.xContentTypeOptions },
    { name: 'Referrer-Policy', status: headers.referrerPolicy },
    { name: 'SPF Email Protection Record', status: dnsAudit.hasSpf },
    { name: 'DMARC Email Security Policy', status: dnsAudit.hasDmarc },
  ];

  headerChecks.forEach((item) => {
    const statusText = item.status ? '[PASS] Configured' : '[FAIL] Missing';
    const color = item.status ? '#16a34a' : '#dc2626';
    doc.fontSize(10).fillColor('#334155').text(`• ${item.name}: `, { continued: true })
       .fillColor(color).text(statusText);
  });

  doc.moveDown(1);

  // Network Port Scan Summary
  const portAudit = scanResult.portAudit || { scannedPortsCount: 10, openPorts: [] };
  doc.fontSize(14).fillColor('#0f172a').text('3. Network Port Probe Summary');
  doc.moveDown(0.5);
  doc.fontSize(10).fillColor('#334155').text(`Scanned Ports: ${portAudit.scannedPortsCount || 10} Common Services`);
  if (portAudit.openPorts && portAudit.openPorts.length > 0) {
    const portListStr = portAudit.openPorts.map(p => `Port ${p.port} (${p.service})`).join(', ');
    doc.fontSize(10).fillColor('#dc2626').text(`Open Detected Ports: ${portListStr}`);
  } else {
    doc.fontSize(10).fillColor('#16a34a').text('Open Detected Ports: None (No public high-risk DB/admin ports found)');
  }

  doc.moveDown(1.5);

  // Vulnerability Findings & Recommendations
  doc.fontSize(14).fillColor('#0f172a').text('4. Detailed Vulnerabilities & Remediation');
  doc.moveDown(0.5);

  if (!scanResult.vulnerabilities || scanResult.vulnerabilities.length === 0) {
    doc.fontSize(10).fillColor('#16a34a').text('No security vulnerabilities detected during this scan. Great job!');
  } else {
    scanResult.vulnerabilities.forEach((vuln, index) => {
      doc.fontSize(11).fillColor('#0f172a').text(`${index + 1}. ${vuln.name} [${vuln.severity.toUpperCase()}]`, { bold: true });
      doc.fontSize(9).fillColor('#475569').text(`   Description: ${vuln.description}`);
      doc.fontSize(9).fillColor('#0284c7').text(`   Fix Recommendation: ${vuln.recommendation}`);
      doc.moveDown(0.8);
    });
  }

  // Footer Page Number
  doc.fontSize(9).fillColor('#94a3b8').text('Confidential - Generated by SecureWeb Platform', 40, 750, { align: 'center' });

  doc.end();
};

/**
 * Generates a downloadable CSV representation of scan results.
 */
export const generateCsvReport = (website, scanResult, res) => {
  res.setHeader('Content-Type', 'text/csv');
  res.setHeader('Content-Disposition', `attachment; filename=SecureWeb-Audit-${website.websiteName.replace(/\s+/g, '_')}.csv`);

  let csvContent = `Website Name,Website URL,Security Score,Risk Level,HTTPS Enabled,Has SPF,Has DMARC,Scan Date\n`;
  const dns = scanResult.dnsAudit || {};
  csvContent += `"${website.websiteName}","${website.websiteURL}",${scanResult.securityScore},"${scanResult.riskLevel}",${scanResult.httpsEnabled},${!!dns.hasSpf},${!!dns.hasDmarc},"${new Date(scanResult.scanDate || Date.now()).toISOString()}"\n\n`;

  csvContent += `Vulnerability Name,Severity,Description,Recommendation\n`;

  if (scanResult.vulnerabilities && scanResult.vulnerabilities.length > 0) {
    scanResult.vulnerabilities.forEach((v) => {
      csvContent += `"${v.name.replace(/"/g, '""')}","${v.severity}","${v.description.replace(/"/g, '""')}","${v.recommendation.replace(/"/g, '""')}"\n`;
    });
  } else {
    csvContent += `"None","Low","No vulnerabilities found","Maintain existing security posture"\n`;
  }

  res.send(csvContent);
};
